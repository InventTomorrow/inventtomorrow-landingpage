/// <reference types="node" />
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { TEAM_TIERS } from '../src/content/team';

// Preserve the original photos; generate only resized, compressed delivery copies.
const targets = [
  ...TEAM_TIERS.flatMap((tier) => tier.members.filter((member) => member.image).map((member) => ({
    source: member.image!, widths: [320, 640, 960], defaultWidth: 640,
  }))),
  { source: '/images/hero-cleaning-automation.jpg', widths: [960, 1600, 2560], defaultWidth: 1600 },
  { source: '/images/about-business-owner-v2.jpg', widths: [320, 640, 960], defaultWidth: 640 },
  { source: '/images/about-systems-team-v3.webp', widths: [320, 640, 960], defaultWidth: 640 },
];

const folder = path.resolve('public/images/optimized');
await mkdir(folder, { recursive: true });
const images: Record<string, { src: string; srcSet: string; width: number; height: number }> = {};
let originalBytes = 0;
let deliveredBytes = 0;

for (const target of targets) {
  const input = await readFile(path.join('public', target.source));
  const name = path.parse(target.source).name;
  const variants = [];
  for (const width of target.widths) {
    const { data, info } = await sharp(input)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, effort: 6, smartSubsample: true })
      .toBuffer({ resolveWithObject: true });
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 12);
    const file = `${name}-${info.width}-${hash}.webp`;
    await writeFile(path.join(folder, file), data);
    variants.push({ src: `/images/optimized/${file}`, width: info.width, height: info.height, bytes: info.size });
  }
  const image = variants.find((variant) => variant.width === target.defaultWidth) ?? variants.at(-1)!;
  images[target.source] = {
    src: image.src,
    srcSet: variants.map((variant) => `${variant.src} ${variant.width}w`).join(', '),
    width: image.width,
    height: image.height,
  };
  originalBytes += input.length;
  deliveredBytes += image.bytes;
  console.log(`${target.source}: ${Math.round(input.length / 1024)} KB -> ${Math.round(image.bytes / 1024)} KB (${image.width}px WebP)`);
}

const manifest = path.resolve('src/content/optimizedImages.ts');
await writeFile(manifest, [
  '// Generated by npm run optimize:images. Do not edit by hand.',
  'export const OPTIMIZED_IMAGES: Record<string, { src: string; srcSet: string; width: number; height: number }> = ',
  JSON.stringify(images, null, 2),
  ';\n',
].join('\n'));
console.log(`Default image payload: ${Math.round(originalBytes / 1024)} KB -> ${Math.round(deliveredBytes / 1024)} KB (${Math.round((1 - deliveredBytes / originalBytes) * 100)}% smaller).`);
